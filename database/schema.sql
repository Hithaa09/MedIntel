-- ---------------------------------------------------------------
-- 4. Analytical views
-- ---------------------------------------------------------------

-- Provider-level roll-up
CREATE OR REPLACE VIEW v_provider_stats AS
SELECT
  provider,
  COUNT(*)                              AS total_claims,
  COUNT(DISTINCT bene_id)               AS unique_patients,
  SUM(inscclaimamtreimbursed)           AS total_reimbursed,
  ROUND(AVG(inscclaimamtreimbursed), 2) AS avg_reimbursed,
  ROUND(AVG(dischargedt - admissiondt), 1) AS avg_los_days,
  RANK() OVER (ORDER BY COUNT(*) DESC)  AS claim_rank
FROM healthcare_claims
WHERE provider IS NOT NULL
GROUP BY provider;

-- Monthly claim volume + spend
CREATE OR REPLACE VIEW v_monthly_trend AS
SELECT
  TRUNC(claimstartdt, 'MM')            AS claim_month,
  TO_CHAR(claimstartdt, 'YYYY-MM')     AS month_label,
  COUNT(*)                             AS total_claims,
  SUM(inscclaimamtreimbursed)          AS total_reimbursed,
  ROUND(AVG(inscclaimamtreimbursed), 2) AS avg_reimbursed
FROM healthcare_claims
WHERE claimstartdt IS NOT NULL
GROUP BY TRUNC(claimstartdt, 'MM'), TO_CHAR(claimstartdt, 'YYYY-MM')
ORDER BY claim_month;

-- High-risk patients (both chronic conditions)
CREATE OR REPLACE VIEW v_patient_risk AS
SELECT
  bene_id,
  dob,
  gender,
  race,
  state,
  chroniccond_diabetes,
  chroniccond_heartfailure,
  CASE
    WHEN chroniccond_diabetes = 1 AND chroniccond_heartfailure = 1 THEN 'High'
    WHEN chroniccond_diabetes = 1 OR  chroniccond_heartfailure = 1 THEN 'Medium'
    ELSE 'Low'
  END                                                             AS risk_level,
  COUNT(claim_id)                                                 AS total_claims,
  SUM(inscclaimamtreimbursed)                                     AS lifetime_reimbursed
FROM healthcare_claims
GROUP BY
  bene_id, dob, gender, race, state,
  chroniccond_diabetes, chroniccond_heartfailure;
