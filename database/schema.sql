-- ---------------------------------------------------------------
-- 2. Main fact table
-- ---------------------------------------------------------------
CREATE TABLE healthcare_claims (
  id                        NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bene_id                   VARCHAR2(50)    NOT NULL,
  dob                       DATE,
  gender                    NUMBER(1),          -- 1=Male  2=Female
  race                      NUMBER(1),          -- CMS codes: 1=White 2=Other 3=Black 5=Hispanic
  state                     NUMBER(3),          -- CMS state codes (1-51)
  chroniccond_diabetes      NUMBER(1),          -- 1=Yes  2=No
  chroniccond_heartfailure  NUMBER(1),          -- 1=Yes  2=No
  claim_id                  VARCHAR2(50)    NOT NULL,
  claimstartdt              DATE,
  claimenddt                DATE,
  provider                  VARCHAR2(50),
  inscclaimamtreimbursed    NUMBER(12, 2)   DEFAULT 0,
  attendingphysician        VARCHAR2(50),
  admissiondt               DATE,
  dischargedt               DATE,
  created_at                TIMESTAMP       DEFAULT SYSTIMESTAMP,

  CONSTRAINT uq_claim_id UNIQUE (claim_id),
  CONSTRAINT chk_gender  CHECK (gender           IN (1, 2)),
  CONSTRAINT chk_diabetes CHECK (chroniccond_diabetes    IN (1, 2)),
  CONSTRAINT chk_hf       CHECK (chroniccond_heartfailure IN (1, 2))
);

-- ---------------------------------------------------------------
